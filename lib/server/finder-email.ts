import "server-only";
import { getTool, pricingLabel } from "@/config/ai-tools";
import { services } from "@/config/services";
import { site } from "@/config/site";
import type { Plan } from "@/lib/stack-finder/types";
import { button, esc, layout, p } from "./email";

/** Full AI stack plan as a branded email. */
export function planEmail(name: string, plan: Plan, runId: string | null) {
  const tools = plan.stack
    .map((s, i) => {
      const t = getTool(s.toolId)!;
      return `<tr><td style="padding:14px 0;border-bottom:1px solid #1d2029;vertical-align:top">
<div style="font-size:12px;color:#C8FF2E;letter-spacing:.12em;text-transform:uppercase">0${i + 1} · ${esc(s.role)}</div>
<div style="font-size:17px;font-weight:600;margin:4px 0"><a href="${t.url}" style="color:#EDEEF2;text-decoration:none">${esc(t.name)}</a> <span style="font-size:12px;color:#8A90A2;font-weight:400">${pricingLabel[t.pricing]}</span></div>
<div style="font-size:14px;color:#C9CCD6;line-height:1.55">${esc(s.why)}</div>
<div style="font-size:13px;color:#8A90A2;line-height:1.55;margin-top:6px"><b style="color:#C9CCD6">Start:</b> ${esc(s.setup)}</div></td></tr>`;
    })
    .join("");
  const steps = plan.workflow
    .map((w, i) => `<li style="margin:0 0 10px;color:#C9CCD6;font-size:14px;line-height:1.55"><b style="color:#EDEEF2">${i + 1}. ${esc(w.title)}</b> — ${esc(w.detail)}</li>`)
    .join("");
  const service = services.find((s) => s.slug === plan.doneForYou.service);
  return layout(`${name.split(" ")[0]}, here's your AI stack: ${plan.headline}`, [
    p(plan.diagnosis),
    `<div style="margin:18px 0;padding:14px 16px;border:1px solid #3d4a12;background:#11160a;border-radius:12px;font-size:14px;color:#EDEEF2"><b style="color:#C8FF2E">Quick win today:</b> ${esc(plan.quickWin)}</div>`,
    `<h2 style="font-size:16px;margin:26px 0 4px">Your stack</h2><table width="100%" cellpadding="0" cellspacing="0">${tools}</table>`,
    `<h2 style="font-size:16px;margin:26px 0 10px">How it works</h2><ol style="padding-left:0;list-style:none;margin:0">${steps}</ol>`,
    `<table width="100%" cellpadding="0" cellspacing="0" style="margin:20px 0;font-size:14px">${[
      ["Time saved", plan.hoursSavedPerWeek + " / week"],
      ["Monthly cost", `${plan.monthlyCostInr} (${plan.monthlyCostUsd})`],
      ["Setup time", plan.setupTime],
      ["Difficulty", plan.difficulty],
    ]
      .map(([k, v]) => `<tr><td style="padding:6px 12px 6px 0;color:#8A90A2">${k}</td><td style="padding:6px 0;color:#EDEEF2">${esc(v)}</td></tr>`)
      .join("")}</table>`,
    `<h2 style="font-size:16px;margin:22px 0 8px">Watch out for</h2><ul style="padding-left:18px;margin:0 0 18px;color:#C9CCD6;font-size:14px;line-height:1.55">${plan.watchOuts.map((w) => `<li>${esc(w)}</li>`).join("")}</ul>`,
    `<div style="margin:26px 0 8px;padding:18px;border-radius:12px;background:#C8FF2E;color:#0A0D02"><div style="font-weight:700;font-size:16px">Want us to build this for you?</div><div style="font-size:14px;margin:6px 0 12px">${esc(plan.doneForYou.pitch)}</div><a href="${site.calendlyUrl}" style="display:inline-block;background:#0A0D02;color:#C8FF2E;text-decoration:none;font-weight:600;font-size:14px;padding:10px 18px;border-radius:999px">Book a free 30-min strategy call</a></div>`,
    service ? p(`Related service: ${service.title} — ${site.url}/services/${service.slug}`) : "",
    runId ? button(`${site.url}/tools/ai-stack-finder?plan=${runId}`, "View your plan online") : "",
    `<p style="margin:16px 0 0;font-size:12px;color:#8A90A2">Tool pricing changes often — check each vendor for current plans. Recommendations are generated by AI and are guidance, not professional advice.</p>`,
  ].join(""));
}
